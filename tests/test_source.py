import pathlib,json,unittest,sys,hashlib,re
from lupa import LuaRuntime
from jsonschema import Draft7Validator
ROOT=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from generate_data import lua
class SourceTests(unittest.TestCase):
 def test_map_schema(self):
  Draft7Validator(json.loads((ROOT/'data/schema.json').read_text())).validate(json.loads((ROOT/'data/map_ship.json').read_text()))
 def test_generated_mirror_is_reproducible(self):
  expected='-- Generated by tools/generate_data.py; edit canonical data only.\nreturn '+lua(json.loads((ROOT/'data/map_ship.json').read_text()))+'\n'
  self.assertEqual((ROOT/'src/shared/MapShip.lua').read_text(),expected)
 def test_lua_compiles(self):
  vm=LuaRuntime();compile=vm.eval('function(s,n) local f,e=load(s,n); if not f then error(e) end; return true end')
  for path in (ROOT/'src').rglob('*.lua'):
   if path.name!='Types.lua':self.assertTrue(compile(path.read_text(),str(path)))
 def test_ship_graph_and_dimensions(self):
  m=json.loads((ROOT/'data/map_ship.json').read_text());self.assertEqual(m['bounds']['max'],[192,48,48])
  graph={}
  for c in m['connections']:
   if not c['optional']:
    graph.setdefault(c['a'],set()).add(c['b']);graph.setdefault(c['b'],set()).add(c['a'])
  visited=set();todo=['CORR_A']
  while todo:
   n=todo.pop()
   if n not in visited:visited.add(n);todo.extend(graph.get(n,[]))
  for r in m['rooms']:self.assertIn(r['id'],visited)
  for i,a in enumerate(m['rooms']):
   for b in m['rooms'][i+1:]:
    if a['level']==b['level']:
     self.assertFalse(all(a['origin'][axis]<b['origin'][axis]+b['size'][axis] and b['origin'][axis]<a['origin'][axis]+a['size'][axis] for axis in [0,2]))
  for room in m['rooms']:
   for dim in room['size']:self.assertEqual(dim%4,0)
 def test_excluded_features_not_executable(self):
  src='\n'.join(p.read_text() for p in (ROOT/'src').rglob('*.lua'))
  for api in ['MarketplaceService','PromptProductPurchase','ProcessReceipt','TeleportService']:self.assertNotIn(api,src)
if __name__=='__main__':unittest.main()
