#!/usr/bin/env python3
"""Extract the baseline ship map + kit JSON from horrorgame.md into Luau data modules.

horrorgame.md is the canonical, read-only source (it declares itself the source of
truth). This tool never edits it. It writes:

  src/Map/Data/ShipSpec.lua   <- APPENDIX A (map_ship.json)
  src/Map/Data/KitSpec.lua    <- APPENDIX D (kit_pieces.json)

Output is byte-deterministic (sorted keys, fixed float formatting) so tests can
prove the committed modules were generated from the current spec and not edited
by hand.

Usage:  python3 tools/extract_spec.py [--check]
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SPEC = os.path.join(os.path.dirname(ROOT), "horrorgame.md")
OUT_DIR = os.path.join(ROOT, "src", "Map", "Data")

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LUA_KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function",
    "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true",
    "until", "while", "continue", "type", "export",
}


def appendix_json(text, start_marker, end_marker):
    a = text.index(start_marker)
    b = text.index(end_marker, a + len(start_marker))
    block = text[a:b]
    open_i = block.index("```json") + len("```json")
    close_i = block.index("```", open_i)
    return json.loads(block[open_i:close_i])


def fmt_num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if float(v).is_integer():
        return str(int(v))
    return repr(float(v))


def to_lua(value, indent=0):
    pad = "\t" * indent
    inner = "\t" * (indent + 1)
    if value is None:
        return "nil"
    if isinstance(value, bool) or isinstance(value, (int, float)):
        return fmt_num(value)
    if isinstance(value, str):
        return json.dumps(value)  # JSON string escapes are valid Lua for our ASCII data
    if isinstance(value, list):
        if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in value):
            return "{" + ", ".join(fmt_num(x) for x in value) + "}"
        parts = [inner + to_lua(x, indent + 1) + "," for x in value]
        return "{\n" + "\n".join(parts) + "\n" + pad + "}"
    if isinstance(value, dict):
        parts = []
        for k in sorted(value.keys()):
            key = k if (IDENT.match(k) and k not in LUA_KEYWORDS) else "[" + json.dumps(k) + "]"
            parts.append(inner + key + " = " + to_lua(value[k], indent + 1) + ",")
        return "{\n" + "\n".join(parts) + "\n" + pad + "}"
    raise TypeError(type(value))


def module_text(name, source_section, data):
    header = (
        "-- GENERATED by tools/extract_spec.py from horrorgame.md " + source_section + ".\n"
        "-- Do not edit by hand: the spec is canonical. Regenerate with\n"
        "--   python3 tools/extract_spec.py\n"
        "-- " + name + "\n"
    )
    return header + "return " + to_lua(data) + "\n"


def build_outputs():
    with open(SPEC, "r", encoding="utf-8") as f:
        text = f.read()
    ship = appendix_json(text, "# APPENDIX A", "# APPENDIX B")
    kit = appendix_json(text, "# APPENDIX D", "# APPENDIX E")
    return {
        "ShipSpec.lua": module_text("Baseline ship map (map_ship.json)", "APPENDIX A", ship),
        "KitSpec.lua": module_text("Baseline modular kit (kit_pieces.json)", "APPENDIX D", kit),
    }


def main():
    check = "--check" in sys.argv
    outputs = build_outputs()
    stale = []
    for name, text in outputs.items():
        path = os.path.join(OUT_DIR, name)
        if check:
            try:
                with open(path, "r", encoding="utf-8") as f:
                    if f.read() != text:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        else:
            os.makedirs(OUT_DIR, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if check:
        if stale:
            print("STALE:", ", ".join(stale))
            return 1
        print("spec modules up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
