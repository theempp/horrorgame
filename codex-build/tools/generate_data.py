"""Reproducible JSON -> Lua mirror. Run from any directory."""
import json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
def lua(v):
    if isinstance(v,dict): return '{'+','.join('['+json.dumps(k)+']='+lua(x) for k,x in v.items())+'}'
    if isinstance(v,list): return '{'+','.join(map(lua,v))+'}'
    if isinstance(v,bool): return str(v).lower()
    if v is None:return 'nil'
    return json.dumps(v)
if __name__=='__main__':
    (ROOT/'src/shared/MapShip.lua').write_text('-- Generated by tools/generate_data.py; edit canonical data only.\nreturn '+lua(json.loads((ROOT/'data/map_ship.json').read_text()))+'\n')
